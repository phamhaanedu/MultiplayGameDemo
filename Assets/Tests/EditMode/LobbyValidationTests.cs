using System;
using System.Text.RegularExpressions;
using System.Threading.Tasks;
using CapsuleArena.Gameplay.Match;
using CapsuleArena.Networking;
using CapsuleArena.UI.Lobby;
using Fusion;
using NUnit.Framework;
using UnityEngine;
using Assert = NUnit.Framework.Assert;

namespace CapsuleArena.Tests.EditMode
{
    /// <summary>
    /// EditMode unit tests verifying <see cref="LobbyViewController"/> <c>DisplayName</c> validation (including invalid
    /// non-empty &amp; TMP rich-text rejection and <c>"Player_XXXX"</c> blank fallback), <c>RoomCode</c> auto-uppercase
    /// validation, Quick Join empty room code flow, immediate button locking during async Photon handshakes,
    /// 4-slot Room Waiting roster + <c>[HOST]</c> badge + <c>"Open Slot..."</c> labels, Leave Room clean shutdown,
    /// and 10.0s timeout recovery via <see cref="ToastNotificationView"/> (Story 11-1; ADR-0002; TR-rebind-001).
    /// </summary>
    [TestFixture]
    public class LobbyValidationTests
    {
        private sealed class FakeSessionService : INetworkSessionService
        {
            public event Action<string> OnSessionDisconnected;
            public event Action<PlayerRef> OnLocalPlayerSpawned;
            public bool IsSessionActive { get; set; }
            public int StartCallCount { get; private set; }
            public int ShutdownCallCount { get; private set; }
            public string LastRequestedRoomCode { get; private set; }
            public TaskCompletionSource<bool> PendingHandshake { get; set; }

            public Task<bool> StartSharedSessionAsync(string roomCode)
            {
                StartCallCount++;
                LastRequestedRoomCode = roomCode;
                if (PendingHandshake != null)
                {
                    return PendingHandshake.Task;
                }

                IsSessionActive = true;
                OnLocalPlayerSpawned?.Invoke(PlayerRef.FromEncoded(1));
                return Task.FromResult(true);
            }

            public Task ShutdownSessionAsync(string reason = "UserLeft")
            {
                ShutdownCallCount++;
                IsSessionActive = false;
                OnSessionDisconnected?.Invoke(reason);
                return Task.CompletedTask;
            }

            public void SimulateDisconnect(string reason)
            {
                IsSessionActive = false;
                OnSessionDisconnected?.Invoke(reason);
            }
        }

        [Test]
        public void ValidateOrGenerateDisplayNameAndIsValidRoomCode_EnforcesRegexRichTextStripAndBlankFallback()
        {
            string autoGenerated = LobbyViewController.ValidateOrGenerateDisplayName("   ");
            Assert.IsTrue(Regex.IsMatch(autoGenerated, "^Player_[0-9]{4}$"),
                $"Blank DisplayName must generate 'Player_XXXX', got '{autoGenerated}'.");

            Assert.AreEqual("Duelist_01", LobbyViewController.ValidateOrGenerateDisplayName("  Duelist_01  "));
            Assert.AreEqual(string.Empty, LobbyViewController.ValidateOrGenerateDisplayName("ab"), "Too short (<3).");
            Assert.AreEqual(string.Empty, LobbyViewController.ValidateOrGenerateDisplayName("Bad Name!"), "Spaces/symbols rejected.");
            Assert.AreEqual(string.Empty, LobbyViewController.ValidateOrGenerateDisplayName("<color=red>x</color>"), "TMP rich-text tags rejected.");

            Assert.IsTrue(LobbyViewController.IsValidRoomCode("ARENA_01"));
            Assert.IsTrue(LobbyViewController.IsValidRoomCode("duel-99"));
            Assert.IsFalse(LobbyViewController.IsValidRoomCode(""));
            Assert.IsFalse(LobbyViewController.IsValidRoomCode("a!"));
            Assert.IsFalse(LobbyViewController.IsValidRoomCode("THIS_ROOM_CODE_IS_WAY_TOO_LONG_99"));
        }

        [Test]
        public void LobbyViewController_InvalidDisplayNameQuickJoinWaitingRoomSlotsLeaveRoomAndTimeoutRecovery_Verified()
        {
            GameObject lobbyGo = new GameObject("LobbyViewController_Test", typeof(RectTransform));
            GameObject mmGo = new GameObject("MatchManager_LobbyTest");
            try
            {
                LobbyViewController lobby = lobbyGo.AddComponent<LobbyViewController>();
                MatchManager mm = mmGo.AddComponent<MatchManager>();
                FakeSessionService session = new FakeSessionService();
                lobby.Initialize(session, mm);

                // 0. Persistent labels above both Lobby input boxes are present and readable:
                Assert.IsNotNull(lobby.DisplayNameLabel);
                Assert.IsNotNull(lobby.RoomCodeLabel);
                Assert.AreEqual(LobbyViewController.DisplayNameFieldLabelText, lobby.DisplayNameLabel.text);
                Assert.AreEqual(LobbyViewController.RoomCodeFieldLabelText, lobby.RoomCodeLabel.text);

                // 1. Invalid non-empty DisplayName ("ab" and TMP rich-text) in ExecuteJoinRequestAsync -> error toast, 0 StartGame calls:
                lobby.DisplayNameInput.text = "<color=red>x</color>";
                Task<bool> badNameTask = lobby.ExecuteJoinRequestAsync(isQuickJoin: true);
                Assert.IsFalse(badNameTask.Result);
                Assert.AreEqual(0, session.StartCallCount);
                Assert.IsTrue(lobby.ToastView.IsShowing);

                // 2. Invalid Room Code ("a!") on Create/Join -> error toast:
                lobby.DisplayNameInput.text = "Vanguard_1";
                lobby.RoomCodeInput.text = "a!";
                Assert.IsFalse(lobby.ExecuteJoinRequestAsync(isQuickJoin: false).Result);
                Assert.AreEqual(0, session.StartCallCount);

                // 3. Quick Join (isQuickJoin: true) with empty RoomCode -> passes string.Empty to StartSharedSessionAsync & opens Waiting Room!
                lobby.RoomCodeInput.text = "";
                Assert.IsTrue(lobby.ExecuteJoinRequestAsync(isQuickJoin: true).Result);
                Assert.AreEqual(1, session.StartCallCount);
                Assert.AreEqual(string.Empty, session.LastRequestedRoomCode, "Quick Join must pass empty RoomCode.");
                Assert.IsTrue(lobby.IsWaitingRoomVisible);

                // Verify 4-slot roster visuals: Slot 0 shows "Vanguard_1" + active [HOST] badge; Slots 1..3 show "Open Slot..." with hidden [HOST]:
                Assert.AreEqual("Vanguard_1", lobby.SlotPlayerNameTexts[0].text);
                Assert.IsTrue(lobby.SlotHostBadges[0].activeSelf, "Host slot must display [HOST] badge.");
                for (int s = 1; s < 4; s++)
                {
                    Assert.AreEqual("Open Slot...", lobby.SlotPlayerNameTexts[s].text);
                    Assert.IsFalse(lobby.SlotHostBadges[s].activeSelf, $"Non-host slot {s} must hide [HOST] badge.");
                }

                // 4. Leave Waiting Room -> calls ShutdownSessionAsync cleanly & returns to Main Lobby:
                lobby.LeaveWaitingRoomAsync().GetAwaiter().GetResult();
                Assert.AreEqual(1, session.ShutdownCallCount);
                Assert.IsTrue(lobby.IsMainLobbyVisible);
                Assert.IsTrue(lobby.AreActionButtonsInteractable);

                // 5. Pending async handshake -> locks buttons immediately, blocks duplicate clicks, uppercases RoomCode, and recovers on timeout:
                session.PendingHandshake = new TaskCompletionSource<bool>();
                lobby.DisplayNameInput.text = ""; // blank -> Player_XXXX
                lobby.RoomCodeInput.text = "duel_07";

                Task<bool> joinTask = lobby.ExecuteJoinRequestAsync(isQuickJoin: false);
                Assert.IsTrue(lobby.IsHandshakeInProgress);
                Assert.IsFalse(lobby.AreActionButtonsInteractable);

                Assert.IsFalse(lobby.ExecuteJoinRequestAsync(isQuickJoin: true).Result);
                Assert.AreEqual(2, session.StartCallCount);
                Assert.AreEqual("DUEL_07", session.LastRequestedRoomCode);

                session.PendingHandshake.SetResult(true);
                session.IsSessionActive = true;
                Assert.IsTrue(joinTask.Result);
                Assert.IsTrue(lobby.IsWaitingRoomVisible);

                lobby.UpdateWaitingBanner(connectedCount: 2, countdownRemainingSec: 3);
                Assert.AreEqual("Match starting in 3...", lobby.WaitingBannerText.text);

                session.SimulateDisconnect("ConnectionTimeout");
                Assert.IsTrue(lobby.IsMainLobbyVisible);
                Assert.IsTrue(lobby.AreActionButtonsInteractable);
                StringAssert.Contains("ConnectionTimeout", lobby.ToastView.LastMessage);

                // 6. Mid-match join (MatchState.Playing already active) -> auto-hides Lobby/WaitingRoom overlay immediately:
                mm.RegisterOrUpdateStandalonePlayer(PlayerRef.FromEncoded(1), "Host1", isAlive: true);
                mm.RegisterOrUpdateStandalonePlayer(PlayerRef.FromEncoded(2), "Peer2", isAlive: true);
                mm.SimulateStandaloneTicks(1 + MatchManager.CountdownDurationTicks);
                Assert.AreEqual(MatchState.Playing, mm.CurrentMatchState);

                session.PendingHandshake = null;
                lobby.DisplayNameInput.text = "Joiner_3";
                Assert.IsTrue(lobby.ExecuteJoinRequestAsync(isQuickJoin: true).Result);
                Assert.IsFalse(lobby.IsWaitingRoomVisible, "Mid-match join during Playing must hide Waiting Room immediately.");
                Assert.IsFalse(lobby.IsMainLobbyVisible);
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(mmGo);
                UnityEngine.Object.DestroyImmediate(lobbyGo);
            }
        }
    }
}
